import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { lintMigration, checkRepository, renderBaseline } from './check-data-api-permissions.mjs';

const valid = `CREATE TABLE public.notes (id uuid PRIMARY KEY);
ALTER TABLE public.notes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.notes FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.notes TO authenticated, service_role;`;
test('explicit role decisions and RLS pass', () => assert.deepEqual(lintMigration(valid), []));
test('RLS policies alone cannot grant API access', () => {
  const errors = lintMigration('CREATE TABLE public.notes(id uuid); ALTER TABLE public.notes ENABLE ROW LEVEL SECURITY; CREATE POLICY read ON public.notes FOR SELECT TO authenticated USING(true);');
  assert.equal(errors.length, 3);
});
test('private schemas are excluded', () => assert.deepEqual(lintMigration('CREATE TABLE private.secret(id uuid);'), []));
test('comments, quoted SQL examples and routine bodies are not grants', () => {
  assert.equal(lintMigration(`CREATE TABLE public.notes(id uuid); -- GRANT ALL ON public.notes TO anon,authenticated,service_role;
    SELECT 'GRANT ALL ON public.notes TO anon,authenticated,service_role;';
    CREATE FUNCTION f() RETURNS void AS $$ BEGIN EXECUTE 'GRANT ALL ON public.notes TO anon,authenticated,service_role'; END $$ LANGUAGE plpgsql;`).length, 4);
});
test('quoted identifiers and unqualified public tables are supported', () => {
  assert.deepEqual(lintMigration('CREATE TABLE "Notes"(id uuid); ALTER TABLE "public"."Notes" ENABLE ROW LEVEL SECURITY; REVOKE ALL ON TABLE "public"."Notes" FROM anon, authenticated; GRANT ALL ON TABLE "Notes" TO service_role;'), []);
});
test('schema-wide and automatic grants fail', () => {
  assert.equal(lintMigration('GRANT ALL ON ALL TABLES IN SCHEMA public TO anon;').length, 1);
  assert.equal(lintMigration('ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO anon;').length, 1);
});
test('identity and serial sequences require their own decisions', () => {
  for (const type of ['bigserial', 'bigint GENERATED ALWAYS AS IDENTITY']) {
    const sql = valid.replace('id uuid PRIMARY KEY', `id ${type} PRIMARY KEY`);
    assert.equal(lintMigration(sql).length, 3);
    assert.deepEqual(lintMigration(sql + '\nREVOKE ALL ON SEQUENCE public.notes_id_seq FROM anon; GRANT USAGE, SELECT ON SEQUENCE public.notes_id_seq TO authenticated, service_role;'), []);
  }
});
test('standalone sequences and added identity columns are covered', () => {
  assert.equal(lintMigration('CREATE SEQUENCE public.counter;').length, 3);
  assert.equal(lintMigration('ALTER TABLE public.notes ADD COLUMN counter bigint GENERATED BY DEFAULT AS IDENTITY;').length, 3);
});
test('grant on a different object cannot satisfy the decision', () => {
  assert.equal(lintMigration(valid.replaceAll('GRANT SELECT, INSERT, UPDATE, DELETE ON public.notes', 'GRANT SELECT, INSERT, UPDATE, DELETE ON public.other')).length, 2);
});
test('unsupported public table forms fail closed', () => {
  assert.equal(lintMigration('CREATE TABLE public.notes AS SELECT 1 AS id;').length, 1);
  assert.equal(lintMigration('CREATE TABLE public.child PARTITION OF public.parent DEFAULT;').length, 1);
});
test('repository check catches backdated new files and rewritten history', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ww-permission-check-'));
  try {
    fs.mkdirSync(path.join(root, 'supabase/permissions'), { recursive: true });
    const dir = path.join(root, 'supabase/migrations'); fs.mkdirSync(dir);
    const historical = 'SELECT 1;';
    const b = { migration: '20261022001703_explicit_data_api_permissions.sql', tables: [], sequences: [], historicalMigrations: { '20250101000000_old.sql': crypto.createHash('sha256').update(historical).digest('hex') } };
    fs.writeFileSync(path.join(root, 'supabase/permissions/data-api-baseline.json'), JSON.stringify(b));
    fs.writeFileSync(path.join(dir, '20250101000000_old.sql'), historical);
    fs.writeFileSync(path.join(dir, b.migration), renderBaseline(b));
    assert.deepEqual(checkRepository(root).errors, []);
    fs.writeFileSync(path.join(dir, '20240101000000_backdated.sql'), 'CREATE TABLE public.bad(id uuid);');
    assert.equal(checkRepository(root).errors.length, 4);
    fs.writeFileSync(path.join(dir, '20250101000000_old.sql'), 'SELECT 2;');
    assert.ok(checkRepository(root).errors.some(e => e.includes('Historical migration changed')));
    fs.appendFileSync(path.join(dir, b.migration), '-- changed');
    assert.ok(checkRepository(root).errors.some(e => e.includes('differs from reviewed ACL baseline')));
  } finally { fs.rmSync(root, { recursive: true, force: true }); }
});
