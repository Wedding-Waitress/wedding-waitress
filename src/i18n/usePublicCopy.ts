function index(value: unknown, namespace: string, path = '') {
  if (typeof value === 'string') {
    if (!existingKeys.has(normalize(value))) existingKeys.set(normalize(value), { namespace, key: path });
  } else if (value && typeof value === 'object' && !Array.isArray(value)) {
    for (const [key, child] of Object.entries(value)) index(child, namespace, path ? `${path}.${key}` : key);
  }
}
